fn max_abs(values: &[f64]) -> f64 {
    values.iter().fold(0.0, |best, v| f64::max(best, v.abs()))
}

#[track_caller]
fn assert_close(actual: &[f64], expected: &[f64], tol: f64) {
    assert_eq!(actual.len(), expected.len(), "length mismatch");
    let scale = max_abs(expected).max(1.0);
    let worst = actual
        .iter()
        .zip(expected)
        .fold(0.0_f64, |w, (a, e)| w.max((a - e).abs()));
    assert!(
        worst <= tol * scale,
        "max abs error {worst:e} > {:e}\nactual   = {actual:?}\nexpected = {expected:?}",
        tol * scale
    );
}

#[track_caller]
fn assert_rel(actual: f64, expected: f64, tol: f64) {
    assert!(
        (actual - expected).abs() <= tol * expected.abs(),
        "{actual:e} vs {expected:e} (rel tol {tol:e})"
    );
}

#[track_caller]
fn assert_close_f32(actual: &[f32], expected: &[f64], tol: f32) {
    assert_eq!(actual.len(), expected.len());
    let scale = (max_abs(expected) as f32).max(1.0);
    for (a, e) in actual.iter().zip(expected) {
        assert!(
            (a - *e as f32).abs() <= tol * scale,
            "{a} vs {e}\nactual = {actual:?}"
        );
    }
}

fn mm(a: &[f64], b: &[f64], m: usize, k: usize, n: usize) -> Vec<f64> {
    gemm(m, n, k, a, k as isize, 1, b, n as isize, 1)
}

fn transpose<T: Copy>(a: &[T], rows: usize, cols: usize) -> Vec<T> {
    let mut out = Vec::with_capacity(a.len());
    for j in 0..cols {
        for i in 0..rows {
            out.push(a[i * cols + j]);
        }
    }
    out
}

fn eye(n: usize) -> Vec<f64> {
    let mut out = vec![0.0; n * n];
    for i in 0..n {
        out[i * n + i] = 1.0;
    }
    out
}

fn hilbert(n: usize) -> Vec<f64> {
    (0..n * n)
        .map(|index| 1.0 / ((index / n + index % n + 1) as f64))
        .collect()
}

fn sub(a: &[f64], b: &[f64]) -> Vec<f64> {
    a.iter().zip(b).map(|(x, y)| x - y).collect()
}

fn scaled(a: &[f64], factor: f64) -> Vec<f64> {
    a.iter().map(|x| x * factor).collect()
}

fn to_f32(a: &[f64]) -> Vec<f32> {
    a.iter().map(|&x| x as f32).collect()
}

/// Columns of the `rows x cols` matrix `q` are orthonormal: `qT q = I`.
#[track_caller]
fn assert_orthonormal_columns(q: &[f64], rows: usize, cols: usize, tol: f64) {
    let gram = mm(&transpose(q, rows, cols), q, cols, rows, cols);
    assert_close(&gram, &eye(cols), tol);
}

/// Rows of the `rows x cols` matrix `q` are orthonormal: `q qT = I`.
#[track_caller]
fn assert_orthonormal_rows(q: &[f64], rows: usize, cols: usize, tol: f64) {
    let gram = mm(q, &transpose(q, rows, cols), rows, cols, rows);
    assert_close(&gram, &eye(rows), tol);
}

/// The component of largest magnitude in column `col` of a row-major `rows x cols` matrix is positive.
#[track_caller]
fn assert_sign_rule(m: &[f64], rows: usize, cols: usize, col: usize) {
    let mut best = 0.0_f64;
    let mut value = 0.0_f64;
    for row in 0..rows {
        let v = m[row * cols + col];
        if v.abs() > best {
            best = v.abs();
            value = v;
        }
    }
    assert!(value >= 0.0, "column {col} violates the sign rule: {value}");
}

/// Full SVD contract: values match NumPy, `U S Vt = A`, orthonormal factors, descending, sign rule.
#[track_caller]
fn check_svd(a: &[f64], rows: usize, cols: usize, s_numpy: &[f64], tol: f64) {
    let (u, s, vt, k) = svd(a, rows, cols).unwrap();
    assert_eq!(k, rows.min(cols));
    assert_eq!(s.len(), k);
    assert_close(&s, s_numpy, tol);
    assert!(s.windows(2).all(|w| w[0] >= w[1]), "not descending: {s:?}");
    let mut us = u.clone();
    for r in 0..rows {
        for c in 0..k {
            us[r * k + c] *= s[c];
        }
    }
    assert_close(&mm(&us, &vt, rows, k, cols), a, tol);
    assert_orthonormal_columns(&u, rows, k, tol);
    assert_orthonormal_rows(&vt, k, cols, tol);
    for c in 0..k {
        assert_sign_rule(&u, rows, k, c);
    }
}

/// Full eigh contract: values match NumPy, `A v = lambda v`, orthonormal V, ascending, sign rule.
#[track_caller]
fn check_eigh(a: &[f64], n: usize, w_numpy: &[f64], tol: f64) -> Vec<f64> {
    let (w, v) = eigh(a, n).unwrap();
    assert_close(&w, w_numpy, tol);
    assert!(w.windows(2).all(|p| p[0] <= p[1]), "not ascending: {w:?}");
    let av = mm(a, &v, n, n, n);
    let mut lv = v.clone();
    for r in 0..n {
        for c in 0..n {
            lv[r * n + c] *= w[c];
        }
    }
    assert_close(&av, &lv, tol);
    assert_orthonormal_columns(&v, n, n, tol);
    for c in 0..n {
        assert_sign_rule(&v, n, n, c);
    }
    v
}

/// Two eigenvectors/singular vectors agree up to sign.
#[track_caller]
fn assert_columns_match_up_to_sign(
    actual: &[f64],
    expected: &[f64],
    rows: usize,
    cols: usize,
    tol: f64,
) {
    for c in 0..cols {
        let dot: f64 = (0..rows)
            .map(|r| actual[r * cols + c] * expected[r * cols + c])
            .sum();
        let sign = if dot < 0.0 { -1.0 } else { 1.0 };
        for r in 0..rows {
            assert!(
                (sign * actual[r * cols + c] - expected[r * cols + c]).abs() <= tol,
                "column {c} differs: {actual:?} vs {expected:?}"
            );
        }
    }
}

