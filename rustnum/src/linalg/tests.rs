//! NumPy-parity tests for the slice-level linear-algebra kernels.
//!
//! Every `data::*` constant below was produced once by `numpy 2.3.2` (float64 unless noted) from the
//! small inputs listed next to it (inputs are rounded to 3 decimals or come from the integer formulas
//! visible in the tests); nothing here is recomputed by the code under test.  The one-off generator
//! scripts are not part of the repository.
//! Where an exact answer exists (Hilbert determinant and inverse) it was computed with
//! Python `fractions.Fraction`.  Tolerances are normwise: `max|actual - expected| <= tol * max(1, max|expected|)`.

