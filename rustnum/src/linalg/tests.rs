#[test]
fn gemm_large_non_square_matches_numpy_checksums() {
    // 150x130 @ 130x170 with integer entries (exact in f64); also a regression test for the
    // output-aliasing guard, which used to be O((m n)^2) and made this call take minutes.
    let (m, k, n) = (150, 130, 170);
    let a: Vec<f64> = (0..m * k)
        .map(|x| (((x / k) * 7 + (x % k) * 3) % 11) as f64 - 5.0)
        .collect();
    let b: Vec<f64> = (0..k * n)
        .map(|x| (((x / n) * 5 + (x % n) * 2) % 13) as f64 - 6.0)
        .collect();
    let mut c = vec![0.0; m * n];
    gemm_f64(
        m, k, n, 1.0, &a, k as isize, 1, &b, n as isize, 1, 0.0, &mut c, n as isize, 1,
    );
    assert_eq!(c.iter().sum::<f64>(), GBIG_SUM);
    assert_eq!(c.iter().map(|x| x * x).sum::<f64>(), GBIG_SUMSQ);
    assert_eq!(c[0], GBIG_00);
    assert_eq!(c[m * n - 1], GBIG_LAST);
    assert_eq!(c[77 * n + 3], GBIG_MID);
    // Generic kernel agrees on the same inputs.
    let g = gemm(m, n, k, &a, k as isize, 1, &b, n as isize, 1);
    assert_eq!(g, c);
}

#[test]
fn gemm_f64_output_guard_is_fast_for_large_outputs_and_accepts_exotic_layouts() {
    // 1200 x 1200 output with inner dimension 2.  The aliasing guard used to compare every pair of
    // output elements (~1e12 comparisons); it must now be effectively free.
    let n = 1200;
    let a: Vec<f64> = (0..n).flat_map(|i| [(i % 7) as f64, 1.0]).collect();
    let b: Vec<f64> = (0..n)
        .map(|_| 1.0)
        .chain((0..n).map(|j| (j % 5) as f64))
        .collect();
    let mut c = vec![0.0; n * n];
    gemm_f64(
        n, 2, n, 1.0, &a, 2, 1, &b, n as isize, 1, 0.0, &mut c, n as isize, 1,
    );
    for (i, j) in [(0, 0), (6, 4), (1199, 1199), (500, 777)] {
        assert_eq!(c[i * n + j], (i % 7 + j % 5) as f64);
    }
    // Padded rows (leading dimension 5 > 3) and interleaved strides (3, 2) are valid, non-aliasing layouts.
    let (a, b) = ([1.0, 2.0, 3.0, 4.0], [1.0, 0.0, 0.0, 1.0]);
    let mut padded = [9.0; 10];
    gemm_f64(2, 2, 2, 1.0, &a, 2, 1, &b, 2, 1, 0.0, &mut padded, 5, 1);
    assert_eq!(padded, [1.0, 2.0, 9.0, 9.0, 9.0, 3.0, 4.0, 9.0, 9.0, 9.0]);
    let mut interleaved = [9.0; 6];
    gemm_f64(
        2,
        2,
        2,
        1.0,
        &a,
        2,
        1,
        &b,
        2,
        1,
        0.0,
        &mut interleaved,
        3,
        2,
    );
    assert_eq!(interleaved, [1.0, 9.0, 2.0, 3.0, 9.0, 4.0]);
}

