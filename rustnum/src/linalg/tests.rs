#[test]
fn hilbert_8_inverse_error_is_bounded_by_condition_number() {
    // The exact inverse has integer entries up to ~4e10.  Forward error is about cond * eps ~ 3e-6
    // in a normwise sense (measured: 1e-8), so 1e-6 is sound but 1e-12 would be wrong.
    let x = inv(&hilbert(8), 8).unwrap();
    let err = max_abs(&sub(&x, &INV_H8_EXACT));
    assert!(
        err <= 1e-6 * max_abs(&INV_H8_EXACT),
        "inverse error {err:e}"
    );
    assert!(err > 0.0, "Hilbert inverse cannot be exact in f64");
}

#[test]
