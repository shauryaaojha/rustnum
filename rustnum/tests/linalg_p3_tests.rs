#[test]
fn test_blocked_qr_shapes_and_reconstruction_f64() {
    let shapes = [
        (1, 1),
        (2, 2),
        (5, 5),
        (7, 4),
        (4, 7),
        (31, 17),
        (17, 31),
        (32, 32),
        (33, 17),
        (17, 33),
        (63, 63),
        (64, 64),
        (65, 33),
        (33, 65),
        (127, 65),
        (65, 127),
        (128, 128),
        (129, 129),
        (200, 75),
        (75, 200),
    ];
    for &(m, n) in &shapes {
        let a = sample_f64(m, n, m * 17 + n);
        let (q, r) = np::linalg::qr(&a);
        let k = m.min(n);
        assert_eq!(q.shape(), [m, k]);
        assert_eq!(r.shape(), [k, n]);

        // Check Q * R ≈ A
        let recon = q.matmul(&r);
        assert!(
            recon.allclose(&a, 1e-10, 1e-10),
            "QR recon failed for shape ({m}, {n})"
        );

        // Check Q^T * Q ≈ I_k
        let ident = np::eye::<f64>(k);
        let q_orth = q.t().matmul(&q);
        assert!(
            q_orth.allclose(&ident, 1e-10, 1e-10),
            "Q orthogonality failed for shape ({m}, {n})"
        );

        // Check R is upper trapezoidal
        for i in 0..k {
            for j in 0..i {
                assert_eq!(r[[i, j]], 0.0, "R must be upper triangular at [{i}, {j}]");
            }
        }
    }
}

