#[test]
fn test_svd_shapes_and_reconstruction_f64() {
    let shapes = [
        (1, 1),
        (2, 2),
        (5, 5),
        (7, 4),
        (4, 7),
        (16, 16),
        (31, 17),
        (17, 31),
        (32, 32),
        (33, 17),
        (17, 33),
        (63, 63),
        (64, 64),
        (65, 33),
        (33, 65),
        (127, 65),
        (65, 127),
        (128, 128),
    ];
    for &(m, n) in &shapes {
        let a = sample_f64(m, n, m * 29 + n);
        let (u, s, vt) = np::linalg::svd(&a);
        let k = m.min(n);
        assert_eq!(u.shape(), [m, k]);
        assert_eq!(s.shape(), [k]);
        assert_eq!(vt.shape(), [k, n]);

        // 1. Check descending singular values and all non-negative
        let s_vec = s.to_vec();
        for &val in &s_vec {
            assert!(val >= 0.0, "Singular value must be non-negative");
        }
        for i in 0..k.saturating_sub(1) {
            assert!(
                s_vec[i] >= s_vec[i + 1] - 1e-10,
                "Singular values not descending at {i}: {} < {}",
                s_vec[i],
                s_vec[i + 1]
            );
        }

        // 2. Check U * diag(s) * Vt ≈ A
        let recon = (&u * &s).matmul(&vt);
        assert!(
            recon.allclose(&a, 1e-9, 1e-9),
            "SVD recon failed for shape ({m}, {n})"
        );

        // 3. Check U^T * U ≈ I_k and Vt * Vt^T ≈ I_k
        let ident = np::eye::<f64>(k);
        let u_orth = u.t().matmul(&u);
        assert!(
            u_orth.allclose(&ident, 1e-9, 1e-9),
            "U orthogonality failed for shape ({m}, {n})"
        );
        let v_orth = vt.matmul(&vt.t());
        assert!(
            v_orth.allclose(&ident, 1e-9, 1e-9),
            "V orthogonality failed for shape ({m}, {n})"
        );

        // 4. Check sign convention: largest component in each column of U is positive
        for col in 0..k {
            let mut best_val = 0.0f64;
            let mut best_mag = 0.0f64;
            for row in 0..m {
                let val = u[[row, col]];
                if val.abs() > best_mag {
                    best_mag = val.abs();
                    best_val = val;
                }
            }
            assert!(
                best_val >= 0.0,
                "SVD sign convention violated in col {col} for shape ({m}, {n})"
            );
        }
    }
}

