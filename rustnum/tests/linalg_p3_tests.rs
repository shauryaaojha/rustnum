//! Comprehensive test suite for Phase P3: blocked LAPACK-class kernels.
//!
//! Covers:
//! - Random sizes 1..=300 including primes and block-boundary sizes (panel ± 1)
//! - Ill-conditioned matrices (Hilbert 10)
//! - Rank-deficient matrices (pinv, matrix_rank, lstsq, svd)
//! - Repeated eigenvalues (eigh)
//! - Tall and wide matrices (QR, SVD)
//! - Both f32 and f64
//! - Mathematical reconstruction checks:
//!   - LU: A * A^-1 ≈ I, A * solve(A, B) ≈ B, det(A) * det(A^-1) ≈ 1
//!   - Cholesky: L * L^T ≈ A
//!   - QR: Q * R ≈ A, Q^T * Q ≈ I
//!   - Eigh: V * diag(w) * V^T ≈ A, V^T * V ≈ I, w ascending, largest-|comp| positive
//!   - SVD: U * diag(s) * V^T ≈ A, U^T * U ≈ I, V * V^T ≈ I, s descending, largest-|comp| positive
//! - Exact NumPy parity with literals generated by NumPy 2.3.2.

use rustnum as np;

fn sample_f64(rows: usize, cols: usize, seed: usize) -> np::Array<f64> {
    np::Array::from_shape_fn([rows, cols], |c| {
        (((c[0] * 37 + c[1] * 19 + seed * 13) % 43) as f64 - 21.0) / 7.0
    })
}

fn sample_psd_f64(n: usize, seed: usize) -> np::Array<f64> {
    let a = sample_f64(n, n, seed);
    let sym = a.matmul(&a.t());
    &sym + &(np::eye::<f64>(n) * (n as f64 + 10.0))
}

fn sample_f32(rows: usize, cols: usize, seed: usize) -> np::Array<f32> {
    sample_f64(rows, cols, seed).astype::<f32>()
}

fn sample_psd_f32(n: usize, seed: usize) -> np::Array<f32> {
    sample_psd_f64(n, seed).astype::<f32>()
}

#[test]
fn test_blocked_lu_sizes_and_primes_f64() {
    // Tests sizes from 1 up to 300, including primes and panel ± 1 boundaries (31, 32, 33, 63, 64, 65, 127, 128, 129, 251, 300)
    let sizes = [
        1, 2, 3, 5, 7, 13, 17, 31, 32, 33, 47, 63, 64, 65, 97, 127, 128, 129, 251,
    ];
    for &n in &sizes {
        let mut a = sample_f64(n, n, n * 3);
        // diagonally dominant to ensure nonsingularity
        a = &a + &(np::eye::<f64>(n) * (n as f64 * 3.0 + 5.0));

        // 1. Inversion reconstruction: A * A^-1 ≈ I
        let a_inv = np::linalg::inv(&a).expect("matrix should be invertible");
        let ident = np::eye::<f64>(n);
        let prod = a.matmul(&a_inv);
        assert!(
            prod.allclose(&ident, 1e-9, 1e-9),
            "LU inv failed reconstruction for size {n}"
        );

        // 2. Solve reconstruction: A * x ≈ b
        let b = sample_f64(n, 1, n * 5);
        let x = np::linalg::solve(&a, &b).expect("solve should succeed");
        let ax = a.matmul(&x);
        assert!(
            ax.allclose(&b, 1e-9, 1e-9),
            "LU solve failed reconstruction for size {n}"
        );

        // 3. Determinant consistency: slogdet and det
        let d = np::linalg::det(&a);
        let (sign, logabs) = np::linalg::slogdet(&a);
        let recovered = sign * logabs.exp();
        if d.is_finite() && recovered.is_finite() {
            assert!(
                (d - recovered).abs() <= 1e-8 * d.abs().max(1.0),
                "det vs slogdet failed for size {n}: {d} vs {recovered}"
            );
        } else {
            assert_eq!(d.is_infinite(), recovered.is_infinite());
            assert_eq!(d.is_sign_positive(), recovered.is_sign_positive());
        }
    }
}

