#[test]
fn test_symmetric_eigh_sizes_and_primes_f64() {
    let sizes = [
        1, 2, 3, 5, 7, 13, 17, 31, 32, 33, 47, 63, 64, 65, 97, 127, 128, 129,
    ];
    for &n in &sizes {
        let a_raw = sample_f64(n, n, n * 19);
        let a = (&a_raw + &a_raw.t()) * 0.5;
        let (w, v) = np::linalg::eigh(&a);
        assert_eq!(w.shape(), [n]);
        assert_eq!(v.shape(), [n, n]);

        // 1. Check ascending eigenvalues
        let w_vec = w.to_vec();
        for i in 0..n.saturating_sub(1) {
            assert!(
                w_vec[i] <= w_vec[i + 1] + 1e-10,
                "Eigenvalues not ascending at {i}: {} > {}",
                w_vec[i],
                w_vec[i + 1]
            );
        }

        // 2. Check V * diag(w) * V^T ≈ A
        let recon = (&v * &w).matmul(&v.t());
        assert!(
            recon.allclose(&a, 1e-9, 1e-9),
            "Eigh recon failed for size {n}"
        );

        // 3. Check V^T * V ≈ I
        let ident = np::eye::<f64>(n);
        let v_orth = v.t().matmul(&v);
        assert!(
            v_orth.allclose(&ident, 1e-9, 1e-9),
            "V orthogonality failed for size {n}"
        );

        // 4. Check sign convention: largest component in each column is positive
        for col in 0..n {
            let mut best_val = 0.0f64;
            let mut best_mag = 0.0f64;
            for row in 0..n {
                let val = v[[row, col]];
                if val.abs() > best_mag {
                    best_mag = val.abs();
                    best_val = val;
                }
            }
            assert!(
                best_val >= 0.0,
                "Eigh sign convention violated in col {col} for size {n}"
            );
        }
    }
}

